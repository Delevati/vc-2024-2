def log_multiscale_detection(img_gray, sigmas):
    volume = []

    for sigma in sigmas:
        blurred = cv.GaussianBlur(img_gray, (0, 0), sigma)
        lap = cv.Laplacian(blurred, cv.CV_32F, ksize=3)
        volume.append(lap)

    return np.stack(volume, axis=0)

