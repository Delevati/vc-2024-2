def detect_keypoints(gray):
    maxCorners = 500
    qualityLevel = 0.01
    minDistance = 10
    corners = cv.goodFeaturesToTrack(gray, maxCorners, qualityLevel, minDistance)
    keypoints = [cv.KeyPoint(x=float(x), y=float(y), size=7) for [[x, y]] in corners]
